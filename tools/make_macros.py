#!/usr/bin/env python3
"""Generate results_macros.tex (every number quoted in the paper) from the
summary.json exported by export_summary.m.

Usage: python3 make_macros.py summary.json results_macros.tex
"""
import json
import math
import sys

J = json.load(open(sys.argv[1]))
out = []


def num(x, d=2):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return '--'
    s = f'{x:.{d}f}'
    if s.startswith('-') and float(s) == 0:
        s = s[1:]
    return s


def big(x):
    return f'{x:,.0f}'.replace(',', '{,}')


def pval(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return '--'
    if p < 1e-3:
        return '$<$0.001'
    return f'{p:.3f}'


def pexpr(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return 'p\\,\\text{n/a}'
    if p < 1e-3:
        return 'p<0.001'
    return f'p={p:.3f}' if p < 0.1 else f'p={p:.2f}'


def mac(name, value, math_mode=True):
    v = f'\\ensuremath{{{value}}}' if math_mode else value
    out.append(f'\\newcommand{{\\{name}}}{{{v}}}')


P = ['U', 'A', 'N']
words = {5: 'Five', 10: 'Ten', 25: 'TwentyFive', 50: 'Fifty'}

out.append('% generated by make_macros.py from the MATLAB results; do not edit by hand')
# fixed network sizes
mac('Nin', big(J.get('Nin', 38400))); mac('Nhid', big(J.get('Nhid', 2400))); mac('Nweights', big(J.get('Nweights', 256)))
mac('Msec', str(int(J.get('M', 8)))); mac('nUni', str(int(J.get('nUni', 32)))); mac('Nchirps', str(int(J.get('Nc', 256))))
mac('lateStart', str(J['late']))
mac('Nmc', str(J['Nmc'])); mac('NmcAbl', str(J['NmcAbl'])); mac('NmcSweep', str(J['NmcSweep']))
# learning
mac('tConv', str(J['tConv'])); mac('tConvMs', num(J['tConvMs'], 0))
mac('rhoFirst', num(J['rho1'])); mac('rhoLate', num(J['rhoLate'])); mac('rhoLateH', num(J['rhoLateH']))
mac('RcogFirst', num(J['Rcog1'])); mac('RcogNeu', num(J['RcogNeu'])); mac('RcogAlg', num(J['RcogAlg']))
mac('kZeroInit', num(J['kInit'])); mac('kZeroFirst', num(J['k0first'])); mac('kZeroLast', num(J['k0last']))
mac('kPed', num(J['kPed'])); mac('kCyc', num(J['kCyc'])); mac('kVeh', num(J['kVeh']))
mac('notchDrop', num(J['notchDrop'], 0)); mac('kOtherLast', num(J['kOtherLast']))
mac('hidDrop', num(J['hidDrop'], 0)); mac('rateHidFirst', num(J['rateHid1'], 1))
mac('rateHidLate', num(J['rateHidLate'], 1)); mac('rateIn', num(J['rateIn'], 2))
mac('eventsPerCPI', big(J['eventsPerCPI'])); mac('eventsPerSec', big(J['eventsPerCPI'] * 20))
mac('synOps', big(J['synOps'])); mac('denseMACs', big(J['denseMACs']))
mac('opsRatio', num(J['opsRatio'], 0)); mac('Esnn', num(J['Esnn'], 3)); mac('Edense', num(J['Edense'], 3))
mac('Eratio', num(J['Eratio'], 0))
# link budget and interference
mac('EIRP', num(J['EIRP'], 1)); mac('INR', num(J['INR'], 1)); mac('snrTen', num(J['snr10'], 1))
mac('Gproc', num(J['Gproc'], 1)); mac('burstLen', num(J['burstLen'], 0))
mac('SNRvehStart', num(J['tgtSNR'][0][0], 1)); mac('SNRpedStart', num(J['tgtSNR'][1][0], 1))
mac('SNRcycStart', num(J['tgtSNR'][2][0], 1))
fr = J['floorRise']
mac('floorRiseLow', num(min(fr), 0)); mac('floorRiseHigh', num(max(J['floorRiseMax']), 0))
# main metrics per policy
two = {'PDall': 3, 'PDlate': 3, 'PDvehIntf': 3, 'FA': 2, 'OSPAlate': 2, 'OSPAloc': 2, 'OSPAcard': 2,
       'falseTracks': 2, 'posRMSE': 2, 'rangeRMSE': 3, 'ptsVeh': 2, 'dwellOnTgt': 3}
alias = {'PDlate': 'PDlate', 'PDvehIntf': 'PDint', 'OSPAlate': 'OSPA', 'dwellOnTgt': 'dwell'}
for f, d in two.items():
    a = alias.get(f, f)
    for i, p in enumerate(P):
        dd = 2 if (f.startswith('PD') or f == 'dwellOnTgt') else d   # two decimals in the text
        mac(f'{a}{p}', num(J[f][i], dd))
    mac(f'p{a}U', pexpr(J[f + '_pU']))
    mac(f'p{a}A', pexpr(J[f + '_pA']))
    mac(f'p{a}AU', pexpr(J[f + '_pAU']))
for i, p in enumerate(P):
    mac(f'PDearly{p}', num(J['PDearly'][i]))
    mac(f'PDveh{p}', num(J['PDtgt'][i][0])); mac(f'PDped{p}', num(J['PDtgt'][i][1]))
    mac(f'PDcyc{p}', num(J['PDtgt'][i][2]))
    mac(f'nVehIntf{p}', num(J['nVehIntf'][i], 0)); mac(f'bVehIntf{p}', num(J['bVehIntf'][i], 0))
    mac(f'gainPDlate{p}', num(100 * (J['PDlate'][i] / J['PDlate'][0] - 1), 1))

# ---------------------------------------------------------------- Table II rows
def cell(f, i, d):
    m, h = J[f][i], J[f + '_h'][i]
    if m is None or (isinstance(m, float) and math.isnan(m)):
        return '--'
    return f'{num(m, d)} $\\pm$ {num(h, d)}'


rows = [
    ('$P_D$, moving targets', 'PDlate', 3),
    ('$P_D$, vehicle in interference window', 'PDvehIntf', 3),
    ('False moving clusters per CPI$^\\dagger$', 'FA', 2),
    ('OSPA distance (m)', 'OSPAlate', 2),
    ('\\quad localisation component (m)', 'OSPAloc', 2),
    ('\\quad cardinality component (m)', 'OSPAcard', 2),
    ('Fraction of dwell on target sectors', 'dwellOnTgt', 3),
]
lines = []
for lab, f, d in rows:
    lines.append(f'{lab} & {cell(f, 0, d)} & {cell(f, 1, d)} & {cell(f, 2, d)} & '
                 f'{pval(J[f + "_pU"])} & {pval(J[f + "_pA"])} \\\\')
names = ['vehicle', 'pedestrian', 'cyclist']
for k in [1]:                                   # pedestrian (vehicle and cyclist are quoted in the text)
    c = [f'{num(J["PDtgt"][i][k], 3)} $\\pm$ {num(J["PDtgt_h"][i][k], 3)}' for i in range(3)]
    lines.insert(2, f'$P_D$, {names[k]}$^\\dagger$ & {c[0]} & {c[1]} & {c[2]} & '
                 f'{pval(J[f"PDtgt{k+1}_pU"])} & {pval(J[f"PDtgt{k+1}_pA"])} \\\\')
lines.append('\\midrule')
lines.append(f'Cognitive reward $R^{{\\mathrm{{cog}}}}$ & -- & {num(J["RcogAlg"])} $\\pm$ {num(J["RcogAlgH"])} & '
             f'{num(J["RcogNeu"])} $\\pm$ {num(J["RcogNeuH"])} & & \\\\')

out.append('\\newcommand{\\tabMainRows}{%\n' + '\n'.join(lines) + '\n}')

# ---------------------------------------------------------------- Table III rows and ablation macros
abl_key = ['Full', 'Frozen', 'Global', 'Rate', 'Latency', 'Delta', 'Eight', 'Four', 'Excision']
abl_lab = ['Full model', 'No learning', 'Global R-STDP',
           'Plain rate code', 'Latency (TTFS) code', 'Delta (contrast) code',
           '8-bit synapses', '4-bit synapses', '+ interference excision']
lines = []
for i, k in enumerate(abl_key):
    mac(f'abl{k}PD', num(J['ablPD'][i])); mac(f'abl{k}OSPA', num(J['ablOSPA'][i]))
    mac(f'abl{k}Rho', num(J['ablRho'][i])); mac(f'abl{k}Syn', big(J['ablSyn'][i]))
    mac(f'abl{k}E', num(J['ablE'][i], 3)); mac(f'abl{k}PDint', num(J['ablPDint'][i]))
    mac(f'abl{k}FalseTr', num(J['ablFalseTr'][i]))
    lab = abl_lab[i] if i else f'\\textbf{{{abl_lab[i]}}}'
    lines.append(f'{lab} & {num(J["ablPD"][i], 3)} $\\pm$ {num(J["ablPDh"][i], 3)} & '
                 f'{num(J["ablOSPA"][i])} & {num(J["ablRho"][i])} & {big(J["ablSyn"][i])} \\\\')
out.append('\\newcommand{\\tabAblRows}{%\n' + '\n'.join(lines) + '\n}')
mac('rateCodeFactor', num(J['ablSyn'][3] / J['ablSyn'][0], 0))
mac('frozenRateFactor', num(J['ablRateHid'][1] / J['ablRateHid'][0], 0))
mac('latFactor', num(J['ablSyn'][0] / J['ablSyn'][4], 0)); mac('deltaFactor', num(J['ablSyn'][0] / J['ablSyn'][5], 0))
for i, k in enumerate(abl_key):
    mac(f'abl{k}Conv', str(J['ablConv'][i])); mac(f'abl{k}P', pexpr(J['ablPfull'][i]))

# ---------------------------------------------------------------- interference sweep
lev = ['Off' if e < -100 else {20: 'Twenty', 23: 'TwentyThree', 26: 'TwentySix', 29: 'TwentyNine'}[round(e)]
       for e in J['eirp']]
pol4 = ['U', 'A', 'N', 'Z']
for li, L in enumerate(lev):
    for pi, p in enumerate(pol4):
        mac(f'intfPD{p}{L}', num(J['intfPD'][li][pi]))
        mac(f'intfOSPA{p}{L}', num(J['intfOSPA'][li][pi]))
        mac(f'intfFA{p}{L}', num(J['intfFA'][li][pi]))
        mac(f'intfPDlate{p}{L}', num(J['intfPDlate'][li][pi]))

# ---------------------------------------------------------------- latency sweep
for ti, T in enumerate(J['Tsweep']):
    w = words[T]
    mac(f'latPD{w}', num(J['latPD'][ti])); mac(f'latE{w}', num(J['latE'][ti], 3))
    mac(f'latSyn{w}', big(J['latSyn'][ti])); mac(f'latRho{w}', num(J['latRho'][ti]))
    mac(f'latOSPA{w}', num(J['latOSPA'][ti]))
    mac(f'latConv{w}', str(J['latConv'][ti]))

open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(f'{len(out)} macros written')
